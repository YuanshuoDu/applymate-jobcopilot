export function hasTranslation(lang: Lang, key: string): boolean {
  return Boolean(dict[lang]?.[key])
}

// ── Context ──────────────────────────────────────────────────────────────────

interface I18nContextValue {
  lang: Lang
  t:    (key: string) => string
  setLang: (l: Lang) => void
}

const I18nContext = createContext<I18nContextValue>({
  lang: 'en',
  t:    (key) => key,
  setLang: () => {},
})

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    if (typeof window !== 'undefined') {
      const stored = localStorage.getItem('applymate_lang')
      return LANGUAGES.some(language => language.value === stored) ? stored as Lang : 'en'
    }
    return 'en'
  })

  const setLang = useCallback((l: Lang) => {
    setLangState(l)
    try { localStorage.setItem('applymate_lang', l) } catch {}
  }, [])

  const t = useCallback((key: string): string => {
    return translate(lang, key)
  }, [lang])

  const value = useMemo(() => ({ lang, t, setLang }), [lang, t, setLang])
  return React.createElement(I18nContext.Provider, { value }, children)
}

export function useI18n() {
  return useContext(I18nContext)
}

