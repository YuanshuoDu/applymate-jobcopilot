export const EXTENSION_TRANSLATION_KEYS = Object.keys(zh)

function getExtensionLang(): ExtensionLang {
  try {
    const value = localStorage.getItem('applymate_lang')
    return value === 'zh' ? 'zh' : 'en'
  } catch {
    return 'en'
  }
}

export function useExtensionI18n() {
  const [lang, setLang] = useState<ExtensionLang>(getExtensionLang)
  useEffect(() => {
    const timer = window.setInterval(() => {
      const next = getExtensionLang()
      setLang(current => current === next ? current : next)
    }, 500)
    return () => window.clearInterval(timer)
  }, [])
  return {
    lang,
    t: (english: string) => translateExtension(lang, english),
  }
}

export function translateExtension(lang: ExtensionLang, english: string): string {
  if (lang !== 'zh') return english
  if (zh[english]) return zh[english]
  const withoutEllipsis = english.replace(/\.\.\.$/, '')
  if (zh[withoutEllipsis]) return zh[withoutEllipsis]
  const formatting = english.match(/^Formatting (\d+) fields for analysis$/)
  if (formatting) return `正在整理 ${formatting[1]} 个字段进行分析`
  const generating = english.match(/^Generating answers for (\d+) fields$/)
  if (generating) return `正在为 ${generating[1]} 个字段生成答案`
  return english
}
